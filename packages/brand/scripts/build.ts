/*
 * Builds the brand kit: `pnpm brand:build`.
 *
 * 1. Outlines "Buun Mail" from Geist SemiBold into src/generated/wordmark.ts, so no logo needs the font.
 * 2. Writes the SVG files into src/svg/ from the geometry: marks, lockups, favicon, tiles, the OG card.
 * 3. Rasterises favicons, app icons, the maskable icon, email logos and the OG card into assets/ with resvg, and packs
 *    favicon.ico. app-icon-1024.png feeds `tauri icon`, which writes the desktop set for every platform.
 *
 * Everything it writes is committed. Run it again after changing the geometry, the colours or the font.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

import { Resvg } from '@resvg/resvg-js'
import { parse } from 'opentype.js'
import type { Font } from 'opentype.js'

import { faviconSvg, markSvg, round, tileSvg } from '../src/geometry'
import type { MarkTone } from '../src/geometry'
import { colors } from '../src/tokens'
import { packIco } from './ico'

const root = path.resolve(import.meta.dirname, '..')
const svgDir = path.join(root, 'src/svg')
const assetDir = path.join(root, 'assets')
for (const dir of [svgDir, assetDir, path.join(root, 'src/generated')]) mkdirSync(dir, { recursive: true })
const require = createRequire(import.meta.url)

const written: string[] = []
function write(file: string, data: string | Buffer): void {
  writeFileSync(file, data)
  written.push(path.relative(root, file))
}

function font(pkg: string, file: string): Font {
  const bytes = readFileSync(require.resolve(`${pkg}/files/${file}`))
  return parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength))
}
const geist = font('@fontsource/geist', 'geist-latin-600-normal.woff')
const geistMedium = font('@fontsource/geist', 'geist-latin-500-normal.woff')
const geistMono = font('@fontsource/geist-mono', 'geist-mono-latin-400-normal.woff')

/** Outlines text with a little negative tracking, its ink box moved to start at x, its baseline at y. */
function outline(face: Font, text: string, x: number, y: number, size: number, tracking = -0.015): string {
  let cursor = x
  const parts: string[] = []
  for (const glyph of face.stringToGlyphs(text)) {
    parts.push(glyph.getPath(cursor, y, size).toPathData(2))
    cursor += (glyph.advanceWidth ?? 0) * (size / face.unitsPerEm) + tracking * size
  }
  return parts.join('')
}
function measure(face: Font, text: string, size: number, tracking = -0.015): number {
  return face.stringToGlyphs(text).reduce((sum, glyph) => sum + (glyph.advanceWidth ?? 0) * (size / face.unitsPerEm) + tracking * size, 0) - tracking * size
}

// 1. The wordmark at 100px, moved so its ink starts at 0,0.
const SIZE = 100
const NAME = 'Buun Mail'
const box = geist.getPath(NAME, 0, 0, SIZE).getBoundingBox()
const os2 = geist.tables['os2'] as unknown as { sCapHeight: number }
write(
  path.join(root, 'src/generated/wordmark.ts'),
  `/* Generated by scripts/build.ts from Geist SemiBold (fontsource). Do not edit; run the build. */\n\n` +
    `/** "Buun Mail" outlined at ${SIZE}px, its ink box starting at 0,0. */\n` +
    `export const WORDMARK = {\n  width: ${round(measure(geist, NAME, SIZE) - box.x1)},\n  height: ${round(box.y2 - box.y1)},\n  capHeight: ${round((os2.sCapHeight / geist.unitsPerEm) * SIZE)},\n` +
    `  d: '${outline(geist, NAME, -box.x1, -box.y1, SIZE)}',\n} as const\n`,
)

// The lockups and OG card read the generated wordmark, so they load after it is written.
const { lockupSvg } = await import('../src/lockup')
const { ogSvg, OG } = await import('../src/og')

// 2. SVG files.
const TONES: MarkTone[] = ['on-dark', 'on-light', 'mono', 'white', 'black']
for (const tone of TONES) {
  write(path.join(svgDir, `mark-${tone}.svg`), markSvg(tone))
  write(path.join(svgDir, `lockup-horizontal-${tone}.svg`), lockupSvg('horizontal', tone, 40))
  write(path.join(svgDir, `lockup-stacked-${tone}.svg`), lockupSvg('stacked', tone, 96))
}
write(path.join(svgDir, 'favicon.svg'), faviconSvg())
write(path.join(svgDir, 'app-icon.svg'), tileSvg(1024))
write(path.join(svgDir, 'app-icon-light.svg'), tileSvg(1024, { ground: 'paper' }))

const ROUTES = [
  { to: 'billing@acme.com', where: 'Acme', folder: 'Receipts' },
  { to: 'hello@globex.io', where: 'Globex', folder: 'Inbox' },
  { to: 'me@personal.dev', where: 'Personal', folder: 'Inbox' },
]
const headline = ['Every address you run.', 'One inbox.'].map((line, index) => `<path d="${outline(geist, line, 80, 270 + index * 70, 58)}"${index === 1 ? ` fill="${colors.paperMuted}"` : ''}/>`).join('')
const arrowX = 80 + Math.max(...ROUTES.map((route) => measure(geistMono, route.to, 24, 0))) + 28
const routes = ROUTES.map((route, index) => {
  const y = 430 + index * 50
  const whereX = arrowX + 52
  const whereWidth = measure(geistMedium, route.where, 24)
  return (
    `<path d="${outline(geistMono, route.to, 80, y, 24, 0)}" fill="${colors.paperMuted}"/>` +
    `<path d="M${round(arrowX)} ${y - 8}H${round(arrowX + 30)}M${round(arrowX + 22)} ${y - 15}L${round(arrowX + 30)} ${y - 8}L${round(arrowX + 22)} ${y - 1}" stroke="${colors.brand}" stroke-width="2.5" fill="none" stroke-linecap="round" stroke-linejoin="round"/>` +
    `<path d="${outline(geistMedium, route.where, whereX, y, 24)}" fill="${colors.paper}"/>` +
    `<path d="${outline(geistMedium, route.folder, whereX + whereWidth + 12, y, 24)}" fill="${colors.paperMuted}"/>`
  )
}).join('')
const og = ogSvg({ headline, routes })
write(path.join(svgDir, 'og-default.svg'), og)

// 3. PNGs and the ICO.
function png(svg: string, width: number): Buffer {
  return new Resvg(svg, { fitTo: { mode: 'width', value: width }, font: { loadSystemFonts: false } }).render().asPng()
}
const favicons = [16, 32, 48].map((size) => ({ size, png: png(tileSvg(size), size) }))
for (const { size, png: bytes } of favicons) write(path.join(assetDir, `favicon-${size}.png`), bytes)
write(path.join(assetDir, 'favicon.ico'), packIco(favicons))
write(path.join(assetDir, 'apple-touch-icon.png'), png(tileSvg(180, { maskable: true }).replace(/rx="0"/, 'rx="0"'), 180))
write(path.join(assetDir, 'icon-192.png'), png(tileSvg(192), 192))
write(path.join(assetDir, 'icon-512.png'), png(tileSvg(512), 512))
write(path.join(assetDir, 'maskable-512.png'), png(tileSvg(512, { maskable: true }), 512))
write(path.join(assetDir, 'app-icon-1024.png'), png(tileSvg(1024), 1024))
write(path.join(assetDir, 'og-default.png'), png(og, OG.width))
for (const [name, tone] of [['email-logo-dark', 'on-dark'], ['email-logo-light', 'on-light']] as const) {
  const svg = lockupSvg('horizontal', tone, 32)
  const width = Number(/width="([\d.]+)"/.exec(svg)?.[1] ?? '160')
  write(path.join(assetDir, `${name}.png`), png(svg, Math.round(width)))
  write(path.join(assetDir, `${name}@2x.png`), png(svg, Math.round(width * 2)))
}
write(
  path.join(assetDir, 'site.webmanifest'),
  `${JSON.stringify(
    {
      name: 'Buun Mail',
      short_name: 'Buun Mail',
      icons: [
        { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
        { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
        { src: 'maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
      theme_color: colors.ink,
      background_color: colors.ink,
      display: 'standalone',
    },
    null,
    2,
  )}\n`,
)

process.stdout.write(`Wrote ${written.length} files:\n${written.map((file) => `  ${file}`).join('\n')}\n`)
